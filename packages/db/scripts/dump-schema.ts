/** Write `public-schema.sql`, `metrics-schema.sql` and `auth-schema.sql` from the running stack.
 *
 * `public-schema.sql` is the current shape of the `public` schema, constraints and all.
 * Migrations are history, and `src/generated/` carries shape but no constraints; this is the file
 * that answers "what does this table look like right now" without reading either.
 *
 * `auth-schema.sql` is the `auth` schema GoTrue creates, self-contained enough to restore into a
 * fresh database created from `template0`. Its contents are decided entirely by the GoTrue version
 * the pinned Supabase CLI ships — see the `::notice::` in the `ts-db-types` CI job for what to do
 * when it drifts.
 *
 * Run through `pnpm db:gen-types`. `TEST_DB=1` selects the test stack, as everywhere.
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = fileURLToPath(new URL('../../..', import.meta.url));

function dumpSchema(schema: string): string {
  const dump = execFileSync(
    `${REPO_ROOT}/scripts/supabase`,
    ['db', 'dump', '--local', '--keep-comments', '--schema', schema],
    { encoding: 'utf8' },
  );
  // `--keep-comments` also keeps two `-- \restrict <token>` lines whose token is random per
  // run. Strip just those so the output stays byte-stable for CI to diff.
  return dump
    .split('\n')
    .filter((line) => !/^-- \\(un)?restrict /.test(line))
    .join('\n');
}

function writeSchema(schema: string, contents: string): void {
  writeFileSync(
    `${REPO_ROOT}/packages/db/${schema}-schema.sql`,
    `-- Generated by \`pnpm db:gen-types\`. Do not edit.\n${contents}`,
  );
}

writeSchema('public', dumpSchema('public'));

// Kanel never reads `metrics` (see `kanel.config.cjs`), so this is the views' only typed record.
writeSchema('metrics', dumpSchema('metrics'));

// `pg_dump --schema auth` groups a trigger with the table it's defined on, not with the schema
// that owns the function it calls. That means it also picks up `on_auth_user_created`, which is
// ours, not GoTrue's — `001_initial_schema.ts` attaches it to `auth.users` to mirror new signups
// into `public.app_user`. Restoring it here would call a function that doesn't exist yet, since
// migrations run after this file does. Stripping it just leaves migration 001 to create the
// identical trigger once its function exists.
writeSchema(
  'auth',
  dumpSchema('auth').replace(
    /--\n-- Name: [^\n]*; Type: TRIGGER;[^\n]*\n--\n\nCREATE (?:OR REPLACE )?TRIGGER "[^"]+" [^\n]*EXECUTE FUNCTION "public"\.[^\n]*\n\n/g,
    '',
  ),
);
